export function resolveSecondaryServiceDescription(
  service: string,
  primary: string
): string {
  const key = service.trim();
  if (!key) return "";
  const normalized = LEGACY_SECONDARY_SERVICE_ALIASES[key] ?? key;
  const explicit = FREELANCER_SECONDARY_SERVICE_DESCRIPTIONS[normalized];
  if (explicit) return explicit;
  const fallback = PRIMARY_FALLBACK[primary.trim()];
  return fallback
    ? `«${key}» — ${fallback}`
    : `«${key}» — שירות לפרילנסרים באירועים.`;
}
