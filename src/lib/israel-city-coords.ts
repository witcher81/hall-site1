const DEFAULT_CENTER = { lat: 31.5, lng: 34.85 };

function coordsByKey(key: string): { lat: number; lng: number } | null {
  if (ISRAEL_CITY_COORDS[key]) return ISRAEL_CITY_COORDS[key];
  const lower = key.toLowerCase();
  for (const [k, v] of Object.entries(ISRAEL_CITY_COORDS)) {
    if (k.toLowerCase() === lower) return v;
  }
  return null;
}

/** התאמה לרשימה — כולל נרמול מקף/קריית כמו ב־CityDatalist */
export function tryExactCityCoords(city: string): { lat: number; lng: number } | null {
  const trimmed = city.trim();
  if (!trimmed) return null;
  const normalized = normalizeCityNameForLookup(trimmed);
  const keysToTry = [trimmed, normalized].filter((k, i, a) => a.indexOf(k) === i);
  for (const k of keysToTry) {
    const hit = coordsByKey(k);
    if (hit) return hit;
  }
  return null;
}

export function coordsForCity(city: string): { lat: number; lng: number } {
  return tryExactCityCoords(city) ?? DEFAULT_CENTER;
}
