/** נרמול שם עיר לחיפוש במפה — תואם לרשימת ה-datalist ול-OSM */
export function normalizeCityNameForLookup(s: string): string {
  let t = s
    .replace(/\u00a0/g, " ")
    .replace(/[\u200e\u200f\u202a-\u202e\u200c\u200d]/g, "")
    .trim()
    .replace(/\s+/g, " ");
  t = t.replace(/-/g, " ").replace(/\s+/g, " ");
  /** קריית (כתיב רשמי ברשימה) ↔ קרית (מפתחות במערכת) */
  t = t.replace(/קריית/g, "קרית");
  /** יקנעם / יקנעם עילית — כתיב חלופי */
  if (t === "יקנעם" || t.startsWith("יקנעם ")) {
    t = t.replace(/^יקנעם/, "יוקנעם");
  }
  return t.trim();
}

